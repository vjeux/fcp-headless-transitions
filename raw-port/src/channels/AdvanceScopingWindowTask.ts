  // 0xe5af08: cvttsd2si — truncation to signed 64-bit.  NOTE: the x86 opcode
  // is defined to yield 0x8000000000000000 on out-of-range / NaN inputs
  // ("indefinite integer value"). For faithful transcription we don't attempt
  // to reproduce that indefinite-value edge case — the callers presumably
  // ensure a finite in-range value, matching the way FCP is exercised. We
  // straight-line the finite path exactly as the disasm does.
  const sampleCount: bigint = BigInt(Math.trunc(samplesAsDouble));

  // 0xe5af0d
