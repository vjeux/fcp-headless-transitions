  // 0xe5aef4 / 0xe5aef8
  const target: FFAudioDynamicScopingWindow = _this.target_at_0x10;
  const seconds: number = target.scopingWindowSeconds_at_0x200;

  // 0xe5af00: xmm0 *= 30.0 (double)
