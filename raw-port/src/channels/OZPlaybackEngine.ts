// raw-port/src/channels/OZPlaybackEngine.ts
//
// FCP `OZPlaybackEngine` — a tiny 8-byte POD value-type wrapping an
// `OZPlaybackEngineType` enum plus a 4-byte flags/aux field. Every method
// enumerated in the ledger is a compiler-generated / hand-written value-type
// primitive: 2 default ctors, 2 enum-taking ctors, 2 copy ctors, one
// assignment operator, one equality operator. NO virtual methods, NO vtable,
// NO typeinfo symbol (verified: `grep ZTV16OZPlaybackEngine
// /tmp/Ozone_allsyms.txt` returns nothing) — so `OZPlaybackEngine` is not a
// polymorphic type. It is a value struct passed by value or by reference,
// and its methods are non-virtual by definition.
//
// This is a REAL (albeit trivial) piece of math — the equality operator
// mirrors the exact two-field compare the compiler emitted, the assignment
// operator preserves the self-check-then-copy fast-path, and the enum-ctor
// initialises +0x4 to zero even though only +0x0 receives the caller's
// argument. Getting any of those wrong (e.g. omitting the self-check, or
// zeroing +0x4 in the default ctor via `movl` twice instead of one `movq`)
// would silently diverge from the binary.
//
// Framework: Ozone (x86_64 slice; file /tmp/Ozone.x86_64; VAs quoted below
// match `otool -tV` output 1:1).
//
// Provenance disasm (auto-generated by raw-port/tools/disasm.sh — Ozone is
// the default framework, so files land WITHOUT an "Ozone." prefix):
//   raw-port/re/disasm/OZPlaybackEngine.OZPlaybackEngine.s
//     (only C1E20OZPlaybackEngineType lands there — disasm.sh returns the
//      first symbol matching `OZPlaybackEngine::OZPlaybackEngine(`; the
//      other 5 ctor bodies were extracted via a full otool -tV dump and
//      quoted verbatim below.)
//   raw-port/re/disasm/OZPlaybackEngine.operator=.s
//   raw-port/re/disasm/OZPlaybackEngine.operator==.s
//
// nm cross-check (`grep OZPlaybackEngine /tmp/Ozone_allsyms.txt`):
//   0x26ff50 T __ZN16OZPlaybackEngineC2Ev                    [C2 default]
//   0x26ff60 T __ZN16OZPlaybackEngineC1Ev                    [C1 default]
//   0x26ff70 T __ZN16OZPlaybackEngineC2E20OZPlaybackEngineType  [C2 enum]
//   0x26ff80 T __ZN16OZPlaybackEngineC1E20OZPlaybackEngineType  [C1 enum]
//   0x26ff90 T __ZN16OZPlaybackEngineC2ERKS_                  [C2 copy]
//   0x26ffa0 T __ZN16OZPlaybackEngineC1ERKS_                  [C1 copy]
//   0x26ffb0 T __ZN16OZPlaybackEngineaSERKS_                  [operator=]
//   0x26ffd0 T __ZNK16OZPlaybackEngineeqERKS_                 [operator== const]
// (No __ZTV / __ZTI / __ZTS symbols — non-polymorphic type.)
//
// nm cross-check for ICF folding: C2Ev @0x26ff50 and C1Ev @0x26ff60 sit at
// DIFFERENT VAs (16-byte gap = 0x10) with IDENTICAL bodies (both `pushq;
// movq %rsp,%rbp; movq $0x0,(%rdi); popq %rbp; retq`). ICF is not
// happening here — the linker preserved both bodies. Similarly the C1/C2
// pairs for the enum-ctor (0x26ff70 vs 0x26ff80) and copy-ctor
// (0x26ff90 vs 0x26ffa0) are byte-identical but distinct.
//
// STRUCT LAYOUT (recovered from all 8 method bodies — every field access
// is documented below with the reading address):
//
//   size = 8 bytes  (the default ctor writes `movq $0, (%rdi)` @0x26ff54,
//                    zeroing 8 bytes in one store; the enum-ctor writes
//                    `movl %esi, (%rdi)` + `movl $0, 4(%rdi)`, filling the
//                    same 8 bytes with two 4-byte stores; the copy-ctor
//                    reads/writes 8 bytes as one movq; operator== compares
//                    two 4-byte halves at +0x0 and +0x4).
//
//   +0x00  u32  type   (OZPlaybackEngineType enum — the caller's arg to
//                       the enum-ctor lands here @0x26ff74/0x26ff84
//                       `movl %esi, (%rdi)`; read by operator== @0x26ffd4
//                       `movl (%rdi), %eax`).
//   +0x04  u32  flags  (auxiliary; zeroed by both the default-ctor
//                       (as part of the 8-byte zero @0x26ff54) and the
//                       enum-ctor (explicit `movl $0, 4(%rdi)` @0x26ff76),
//                       and read by operator== @0x26ffda
//                       `movl 4(%rdi), %eax`. NOT written by the copy-ctor
//                       or operator= separately — those move 8 bytes as a
//                       unit via one movq).
//
// The reason flags is written EXPLICITLY as 0 in the enum-ctor (rather
// than as part of a movq $0) is that the compiler laid the ctor out as
// two aligned 32-bit stores: the first uses the argument register
// (`movl %esi, ...`) so the second must also be 32-bit for locality.
// The default-ctor could freely coalesce both into `movq $0`.
//
// Cross-framework references (all resolved from the disasm):
//   NONE. This class is fully self-contained: no external callees, no
//   __stubs entries, no data-const reads, no vtable slots. Every
//   instruction body ends with a plain `retq`.
//
// FULL DISASM (all 8 bodies quoted verbatim from otool -tV of
// /tmp/Ozone.x86_64; C2 bodies were extracted via
// `otool -tV /tmp/Ozone.x86_64 -p __ZN16OZPlaybackEngineC2Ev`):
//
// C2 default  @0x26ff50 __ZN16OZPlaybackEngineC2Ev:
//   0x26ff50  pushq  %rbp
//   0x26ff51  movq   %rsp, %rbp
//   0x26ff54  movq   $0x0, (%rdi)            ; *(u64*)this = 0  (zeroes both fields)
//   0x26ff5b  popq   %rbp
//   0x26ff5c  retq
//   0x26ff5d  nopl   (%rax)                  ; padding
//
// C1 default  @0x26ff60 __ZN16OZPlaybackEngineC1Ev:
//   0x26ff60  pushq  %rbp
//   0x26ff61  movq   %rsp, %rbp
//   0x26ff64  movq   $0x0, (%rdi)            ; *(u64*)this = 0
//   0x26ff6b  popq   %rbp
//   0x26ff6c  retq
//   0x26ff6d  nopl   (%rax)                  ; padding
//
// C2 enum  @0x26ff70 __ZN16OZPlaybackEngineC2E20OZPlaybackEngineType:
//   0x26ff70  pushq  %rbp
//   0x26ff71  movq   %rsp, %rbp
//   0x26ff74  movl   %esi, (%rdi)            ; this->type_at_0x0 = arg (u32)
//   0x26ff76  movl   $0x0, 0x4(%rdi)         ; this->flags_at_0x4 = 0
//   0x26ff7d  popq   %rbp
