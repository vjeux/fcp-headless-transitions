//   0x26ff80  pushq  %rbp
//   0x26ff81  movq   %rsp, %rbp
//   0x26ff84  movl   %esi, (%rdi)            ; this->type_at_0x0 = arg (u32)
//   0x26ff86  movl   $0x0, 0x4(%rdi)         ; this->flags_at_0x4 = 0
//   0x26ff8d  popq   %rbp
//   0x26ff8e  retq
//   0x26ff8f  nop                            ; padding
//
// C2 copy  @0x26ff90 __ZN16OZPlaybackEngineC2ERKS_:
//   0x26ff90  pushq  %rbp
//   0x26ff91  movq   %rsp, %rbp
//   0x26ff94  movq   (%rsi), %rax            ; rax = *(u64*)other  (both fields as one word)
//   0x26ff97  movq   %rax, (%rdi)            ; *(u64*)this = rax
//   0x26ff9a  popq   %rbp
//   0x26ff9b  retq
//   0x26ff9c  nopl   (%rax)                  ; padding
//
// C1 copy  @0x26ffa0 __ZN16OZPlaybackEngineC1ERKS_:
//   0x26ffa0  pushq  %rbp
//   0x26ffa1  movq   %rsp, %rbp
//   0x26ffa4  movq   (%rsi), %rax            ; rax = *(u64*)other
//   0x26ffa7  movq   %rax, (%rdi)            ; *(u64*)this = rax
