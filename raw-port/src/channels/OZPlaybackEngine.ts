//   0x26ffab  retq
//   0x26ffac  nopl   (%rax)                  ; padding
//
// operator=  @0x26ffb0 __ZN16OZPlaybackEngineaSERKS_:
//   0x26ffb0  pushq  %rbp
//   0x26ffb1  movq   %rsp, %rbp
//   0x26ffb4  movq   %rdi, %rax              ; rax = this      (return value)
//   0x26ffb7  cmpq   %rsi, %rdi              ; if (this == &other)
//   0x26ffba  je     0x26ffc2                ;   skip copy — self-assignment fast path
//   0x26ffbc  movq   (%rsi), %rcx            ; rcx = *(u64*)other
//   0x26ffbf  movq   %rcx, (%rax)            ; *(u64*)this = rcx   (rax==rdi==this)
//   0x26ffc2  popq   %rbp
//   0x26ffc3  retq
//   0x26ffc4  nopw   %cs:(%rax,%rax)         ; padding
//
// operator== const  @0x26ffd0 __ZNK16OZPlaybackEngineeqERKS_:
//   0x26ffd0  pushq  %rbp
//   0x26ffd1  movq   %rsp, %rbp
//   0x26ffd4  movl   (%rdi), %eax            ; eax = this->type_at_0x0
//   0x26ffd6  cmpl   (%rsi), %eax            ; compare with other->type_at_0x0
//   0x26ffd8  jne    0x26ffe5                ; if not equal -> return false
//   0x26ffda  movl   0x4(%rdi), %eax         ; eax = this->flags_at_0x4
//   0x26ffdd  cmpl   0x4(%rsi), %eax         ; compare with other->flags_at_0x4
//   0x26ffe0  sete   %al                     ; al = (flags equal) ? 1 : 0  (zero-extended
//                                            ;                              on return via ABI)
//   0x26ffe3  popq   %rbp
//   0x26ffe4  retq
//   0x26ffe5  xorl   %eax, %eax              ; return 0 (types differ)
//   0x26ffe7  popq   %rbp
//   0x26ffe8  retq
//   0x26ffe9  nopl   (%rax)                  ; padding
//
// Note the ABI quirk on operator==: the `sete %al` path ONLY sets the low
// byte of rax, leaving the high 56 bits UNDEFINED at the instruction
// level. The System V AMD64 ABI defines `bool` as a zero-extended byte
// return, and the compiler here relies on the caller to only read the
// low byte — the `sete` path is correct precisely because the ABI says so.
// The `xorl %eax, %eax` path explicitly zeros the full rax. From the
// caller's perspective both paths yield a well-defined `bool`.

// ── the value type ───────────────────────────────────────────────────────────────────────────

/**
 * `OZPlaybackEngineType` — the u32 enum stored at OZPlaybackEngine +0x0.
 * Not enumerated here (the specific enum values are not read from any
 * method in this class — every access treats the field as an opaque u32
 * compared for equality). We type it as `number` (u32-shaped) to match
 * the ABI: the enum-ctor receives it in `%esi` @0x26ff74/0x26ff84, a
 * 32-bit-wide register. Downstream code that owns the enum values
 * (whichever class defines them) should re-export a stricter type.
 */
export type OZPlaybackEngineType = number;

/**
 * `OZPlaybackEngine` — 8-byte POD value type (see STRUCT LAYOUT above).
 * We mirror the exact 2-field layout the compiler used; every method
 * below reads/writes these two fields with the same offsets as the
 * disasm.
 */
export interface OZPlaybackEngine {
  /**
   * `+0x00` — u32 enum. Written by:
   *   - default ctors @0x26ff54 / 0x26ff64 (via `movq $0`, half of the qword)
   *   - enum ctors    @0x26ff74 / 0x26ff84 (`movl %esi, (%rdi)`)
   *   - copy ctors    @0x26ff97 / 0x26ffa7 (via `movq`, half of the qword)
   *   - operator=     @0x26ffbf (via `movq`, half of the qword)
   * Read by:
   *   - operator==    @0x26ffd4 (`movl (%rdi), %eax`)
   */
  type_at_0x0: OZPlaybackEngineType;
  /**
   * `+0x04` — u32 aux/flags. Written by:
   *   - default ctors @0x26ff54 / 0x26ff64 (via `movq $0`, half of the qword)
   *   - enum ctors    @0x26ff76 / 0x26ff86 (`movl $0, 4(%rdi)`)
   *   - copy ctors    @0x26ff97 / 0x26ffa7 (via `movq`, half of the qword)
   *   - operator=     @0x26ffbf (via `movq`, half of the qword)
   * Read by:
   *   - operator==    @0x26ffda (`movl 4(%rdi), %eax`)
   */
  flags_at_0x4: number;
}

// ── ported methods ───────────────────────────────────────────────────────────────────────────

/**
 * `OZPlaybackEngine::OZPlaybackEngine()` [C2 = C1 default ctor]
 * @Ozone 0x26ff50 (__ZN16OZPlaybackEngineC2Ev) — same body at 0x26ff60
 * (__ZN16OZPlaybackEngineC1Ev).
 *
 * Zeroes both fields with a single 8-byte store (`movq $0x0, (%rdi)`
 * @0x26ff54 / 0x26ff64).
 */
export function OZPlaybackEngine_default_ctor(this_: OZPlaybackEngine): void {
  // 0x26ff54: movq $0x0, (%rdi)  — zeroes both fields in one shot.
  this_.type_at_0x0 = 0;
  this_.flags_at_0x4 = 0;
}

/**
 * `OZPlaybackEngine::OZPlaybackEngine(OZPlaybackEngineType)` [C2 = C1 enum ctor]
 * @Ozone 0x26ff70 (__ZN16OZPlaybackEngineC2E20OZPlaybackEngineType) —
 * same body at 0x26ff80 (__ZN16OZPlaybackEngineC1E20OZPlaybackEngineType).
 *
 * Sets `type_at_0x0` to the caller's argument (`movl %esi, (%rdi)`
 * @0x26ff74 / 0x26ff84) and explicitly zeros `flags_at_0x4`
 * (`movl $0x0, 0x4(%rdi)` @0x26ff76 / 0x26ff86) — the two separate
 * 32-bit stores that the compiler emitted (not coalesced into a movq
 * because one operand is a register).
 */
export function OZPlaybackEngine_ctor_type(
  this_: OZPlaybackEngine,
  type: OZPlaybackEngineType,
): void {
  // 0x26ff74 / 0x26ff84: movl %esi, (%rdi)
  this_.type_at_0x0 = type;
  // 0x26ff76 / 0x26ff86: movl $0x0, 0x4(%rdi)
  this_.flags_at_0x4 = 0;
}

/**
 * `OZPlaybackEngine::OZPlaybackEngine(OZPlaybackEngine const&)` [C2 = C1 copy ctor]
 * @Ozone 0x26ff90 (__ZN16OZPlaybackEngineC2ERKS_) — same body at
 * 0x26ffa0 (__ZN16OZPlaybackEngineC1ERKS_).
 *
 * Copies both fields as one 64-bit word (`movq (%rsi), %rax` @0x26ff94 /
 * 0x26ffa4; `movq %rax, (%rdi)` @0x26ff97 / 0x26ffa7). No self-check
 * (the copy-ctor is only ever called at object construction, when the
 * source and dest are guaranteed distinct).
 */
export function OZPlaybackEngine_copy_ctor(
  this_: OZPlaybackEngine,
  other: OZPlaybackEngine,
): void {
  // 0x26ff94 / 0x26ffa4: movq (%rsi), %rax
  // 0x26ff97 / 0x26ffa7: movq %rax, (%rdi)
  this_.type_at_0x0 = other.type_at_0x0;
  this_.flags_at_0x4 = other.flags_at_0x4;
}

/**
 * `OZPlaybackEngine::operator=(OZPlaybackEngine const&)`
 * @Ozone 0x26ffb0 (__ZN16OZPlaybackEngineaSERKS_).
 *
 * Copy-assignment with the classic self-assignment fast-path guard:
 *   if (this == &other) return *this;
 *   *(u64*)this = *(u64*)&other;
 *   return *this;
 *
 * The 8-byte block copy is emitted via a single movq load + store
 * (@0x26ffbc `movq (%rsi), %rcx`; @0x26ffbf `movq %rcx, (%rax)` where
 * rax == this saved @0x26ffb4). Returns `this` — matching the ABI where
 * the return value in rax was pre-populated @0x26ffb4 with `movq %rdi,
 * %rax` BEFORE the compare, so both branches (self-assign and copy)
 * exit with rax == this.
 */
export function OZPlaybackEngine_operator_assign(
  this_: OZPlaybackEngine,
  other: OZPlaybackEngine,
): OZPlaybackEngine {
  // 0x26ffb4: movq %rdi, %rax  — return value = this (pre-populated).
  // 0x26ffb7: cmpq %rsi, %rdi
  // 0x26ffba: je 0x26ffc2      — self-assignment: skip the copy.
  if (this_ !== other) {
    // 0x26ffbc: movq (%rsi), %rcx
    // 0x26ffbf: movq %rcx, (%rax)   ; rax == rdi == this_
    this_.type_at_0x0 = other.type_at_0x0;
    this_.flags_at_0x4 = other.flags_at_0x4;
  }
  // 0x26ffc2..0x26ffc3: pop rbp; ret  — rax still == this_.
  return this_;
}

/**
 * `OZPlaybackEngine::operator==(OZPlaybackEngine const&) const`
 * @Ozone 0x26ffd0 (__ZNK16OZPlaybackEngineeqERKS_).
 *
 * Two 32-bit field-wise compares. NOT a single 64-bit compare — the
 * compiler emitted:
 *   if (this->+0x0 != other->+0x0) return false;      // @0x26ffd4..0x26ffd8
 *   return this->+0x4 == other->+0x4;                 // @0x26ffda..0x26ffe0
 * The behaviour is IDENTICAL to a single 64-bit compare for the well-
 * defined enum+flags representation (both fields are plain integers, no
 * padding, no float NaN quirks), but we mirror the two-step compare
 * because that is what the machine does — a padding-tolerant implementer
 * writing a wider compare would silently produce different results if
 * this struct ever grew padding.
 */
export function OZPlaybackEngine_operator_eq(
  this_: OZPlaybackEngine,
  other: OZPlaybackEngine,
): boolean {
  // 0x26ffd4: movl (%rdi), %eax
  // 0x26ffd6: cmpl (%rsi), %eax
  // 0x26ffd8: jne 0x26ffe5   — return false path
  if ((this_.type_at_0x0 | 0) !== (other.type_at_0x0 | 0)) {
    // 0x26ffe5: xorl %eax, %eax; retq  -> false
    return false;
  }
  // 0x26ffda: movl 0x4(%rdi), %eax
  // 0x26ffdd: cmpl 0x4(%rsi), %eax
  // 0x26ffe0: sete %al       -> bool result
  return (this_.flags_at_0x4 | 0) === (other.flags_at_0x4 | 0);
}
